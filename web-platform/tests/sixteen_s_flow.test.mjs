// 16S workflow tests. Everything here is offline; no NCBI call is made and no
// synthetic value is ever described as a real result.
import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

import { ALLOWED_DATABASE, ALLOWED_PROGRAM, MOCK_TSV } from "../functions/api/blast/_lib.js";
import { handleCreateRequest } from "../functions/api/ai/requests/index.js";
import { handleApprove } from "../functions/api/ai/plans/[id]/approve.js";
import { createFakeD1AI, makePostRequest, mockAIEnv } from "./helpers/fake-d1.mjs";

const NOW = Date.parse("2026-11-25T12:00:00.000Z");
const FASTA = ">seq1 16S isolate\nACGTACGTACGTACGTACGT\n>seq2 16S isolate\nACGTACGTTCGTACGTACGT\n";

test("request -> approval issues a consent token bound to the exact BLAST constants", async () => {
  const fake = createFakeD1AI();
  const env = mockAIEnv(fake.db);

  const created = await handleCreateRequest(makePostRequest({
    text: "Identify taxa from these 16S sequences using BLASTN",
    fasta: FASTA,
    filename: "16s.fasta"
  }, "/api/ai/requests"), env, { now: NOW });
  assert.equal(created.status, 200);
  const request = await created.json();
  assert.equal(request.plan.intent, "identify_taxa");
  assert.equal(request.plan.steps[0].tool_id, "ncbi.blastn");
  assert.deepEqual(request.plan.steps[0].params, { database: ALLOWED_DATABASE, program: ALLOWED_PROGRAM });
  assert.equal(request.plan.steps[0].external_egress, true);
  assert.equal(request.plan.steps[0].consent_required, true);

  const approved = await handleApprove(makePostRequest({
    approvals: [{ step_id: "step_1", approved: true, consent_granted: true }],
    consents: ["external-blast"]
  }, `/api/ai/plans/${request.plan_id}/approve`), env, request.plan_id, { now: NOW });
  assert.equal(approved.status, 200);
  const approval = await approved.json();
  assert.equal(approval.job_ids.length, 1);
  assert.ok(approval.blast_consent?.token, "approval must issue a single-use BLAST consent token");
  assert.equal(approval.blast_consent.database, ALLOWED_DATABASE);
  assert.equal(approval.blast_consent.program, ALLOWED_PROGRAM);
  assert.equal(approval.blast_consent.input_hash.length, 64);
  assert.ok(approval.blast_consent.expires_at);
});

test("approval without explicit consent creates no job and issues no token", async () => {
  const fake = createFakeD1AI();
  const env = mockAIEnv(fake.db);
  const created = await handleCreateRequest(makePostRequest({
    text: "Identify taxa using BLAST", fasta: FASTA, filename: "16s.fasta"
  }, "/api/ai/requests"), env, { now: NOW });
  const request = await created.json();
  const denied = await handleApprove(makePostRequest({
    approvals: [{ step_id: "step_1", approved: true, consent_granted: false }],
    consents: []
  }, `/api/ai/plans/${request.plan_id}/approve`), env, request.plan_id, { now: NOW });
  const body = await denied.json();
  assert.deepEqual(body.job_ids, []);
  assert.equal(body.blast_consent, undefined);
  assert.equal(body.skipped[0].reason, "consent_denied");
});

